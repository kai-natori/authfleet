import { readdir, readFile, writeFile } from "node:fs/promises";

const directory = new URL("../migrations/", import.meta.url);
const names = (await readdir(directory)).filter((name) => name.endsWith(".sql")).sort();
const migrations = await Promise.all(
  names.map(async (name) => ({ name, sql: await readFile(new URL(name, directory), "utf8") })),
);
await writeFile(
  new URL("../src/db/migrations.generated.ts", import.meta.url),
  `// Generated by pnpm db:bundle.\nexport const migrations = ${JSON.stringify(migrations, null, 2)};\n`,
);
